export const LOCALES = ["en", "es"] as const;
export type Locale = (typeof LOCALES)[number];
export const STRINGS: Record<Locale, Record<StringKey, string>> = { en, es };

/** Fills {placeholders}. A missing value leaves the placeholder visible, so it's caught in review. */
export function translate(locale: Locale, key: StringKey, vars?: Record<string, string | number>): string {
  const text = STRINGS[locale][key] ?? en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m)) : text;
}
